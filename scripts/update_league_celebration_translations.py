def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def replace_key(content: str, key: str, value: str) -> str:
    # Допускаем лишнюю кавычку после = (после ошибочного прогона).
    pattern = rf'^("{re.escape(key)}"\s*=\s*)"+(.+)";\s*$'
    repl = rf'\1"{esc(value)}";'
    new_content, n = re.subn(pattern, repl, content, count=1, flags=re.MULTILINE)
    if n != 1:
        print(f"  WARN: key not replaced once: {key} (matches={n})")
    return new_content


