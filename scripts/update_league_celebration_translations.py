def patch_file(path: Path, lang: str) -> bool:
    if lang not in TRANSLATIONS:
        print(f"SKIP no translations: {lang} ({path})")
        return False
    d = TRANSLATIONS[lang]
    text = path.read_text(encoding="utf-8")
    original = text
    for key in KEYS_ORDER:
        if key not in d:
            print(f"MISSING key in dict {lang}: {key}")
            continue
        text = replace_key(text, key, d[key])
    if text == original:
        print(f"NO CHANGE {path}")
        return False
    path.write_text(text, encoding="utf-8")
    return True


def main() -> None:
    ok = 0
    for lproj in sorted(RES.glob("*.lproj")):
        lang = lproj.name.replace(".lproj", "")
        f = lproj / "Localizable.strings"
        if not f.is_file():
            continue
        if patch_file(f, lang):
            print(f"OK {f.relative_to(ROOT)}")
            ok += 1
    print(f"Updated {ok} files.")


if __name__ == "__main__":
    main()
