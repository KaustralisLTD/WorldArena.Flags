import Foundation
let fresh = LevelProgression.State.migrate(level: 1, totalXP: 0)
assert(fresh.advanced(to: 1000).level == 1)
assert(fresh.advanced(to: 2500).level == 2)
let legacy = LevelProgression.State.migrate(level: 100, totalXP: 99000)
assert(legacy.level == 100 && legacy.remaining == 52000)
assert(legacy.advanced(to: 105000).level == 100)
assert(legacy.advanced(to: 151000).level == 101)
let partlyDone = LevelProgression.State.migrate(level: 50, totalXP: 49500)
assert(abs(partlyDone.fraction - 0.5) < 0.0001)
let saved = try! JSONDecoder().decode(LevelProgression.State.self, from: JSONEncoder().encode(partlyDone))
assert(saved == partlyDone)
let earned = legacy.advanced(to: 105000)
assert(earned.advanced(to: 105000) == earned)
assert(earned.advanced(to: 100000).progressXP == earned.progressXP)
assert(earned.advanced(to: 106000).progressXP == 7000)
assert(LevelProgression.highestCelebration(from: 49, through: 102) == 100)
assert(LevelProgression.highestCelebration(from: 100, through: 105) == nil)
assert(!LevelProgression.isCelebrationLevel(101))
print("Level progression, migration, persistence and sparse celebrations passed")
