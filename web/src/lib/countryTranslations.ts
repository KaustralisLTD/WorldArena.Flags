// Функция для получения перевода названия страны
export function getCountryTranslation(countryName: string, language: string): string | null {
  const translations = countryTranslations[language];
  if (!translations) {
    console.log(`No translations found for language: ${language}`);
    return null;
  }
  
  const translation = translations[countryName];
  
  if (language === 'uk') {
    console.log(`\n=== Country Translation Debug ===`);
    console.log(`Country name: "${countryName}"`);
    console.log(`Language: ${language}`);
    console.log(`Translation found: ${translation ? `"${translation}"` : 'NO'}`);
    console.log(`Available keys sample:`, Object.keys(translations).slice(0, 5));
    console.log(`================================\n`);
  }
  
  return translation || null;
} 